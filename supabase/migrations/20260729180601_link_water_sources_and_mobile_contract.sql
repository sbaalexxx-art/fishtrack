-- Promote normalized AFDJ staging observations into the canonical,
-- append-only operational Water store.
create or replace function public.promote_afdj_water_level_observations()
returns integer
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  inserted_rows integer := 0;
begin
  if not exists (
    select 1
    from public.water_data_sources
    where source_key = 'AFDJ'
      and country_code = 'RO'
      and is_active
  ) then
    raise exception
      'AFDJ promotion failed: active source registry entry is missing.';
  end if;

  if exists (
    select 1
    from public.water_observations_staging staging
    left join public.water_station_source_mappings mapping
      on mapping.source = staging.source
     and mapping.country_code = staging.country_code
     and mapping.source_station_id = staging.station_key
     and mapping.mapping_status = 'verified'
    where staging.source = 'AFDJ'
      and staging.country_code = 'RO'
      and mapping.station_id is null
  ) then
    raise exception
      'AFDJ promotion failed: one or more staging stations are not verified.';
  end if;

  insert into public.water_operational_observations (
    source_id,
    country_code,
    source_entity_id,
    station_id,
    metric_code,
    metric_name,
    value,
    unit,
    availability_status,
    observed_at,
    observed_at_precision,
    quality_status,
    confidence,
    source_record_id,
    source_record_fingerprint,
    source_url,
    ingestion_run_id,
    fetched_at,
    raw_payload
  )
  select
    source_registry.id,
    staging.country_code,
    staging.station_key,
    mapping.station_id,
    'water_level_cm',
    'Water level',
    staging.water_level_cm,
    'cm',
    'available',
    staging.observed_at,
    'exact',
    'validated',
    'high',
    coalesce(
      staging.source_record_uuid,
      staging.source_record_id::text,
      staging.id::text
    ),
    encode(
      digest(
        concat_ws(
          '|',
          staging.source,
          staging.country_code,
          staging.station_key,
          'water_level_cm',
          extract(epoch from staging.observed_at)::text,
          staging.water_level_cm::text,
          coalesce(
            staging.source_record_uuid,
            staging.source_record_id::text,
            ''
          )
        ),
        'sha256'
      ),
      'hex'
    ),
    staging.source_url,
    concat(
      'afdj-staging-',
      to_char(
        staging.ingested_at at time zone 'UTC',
        'YYYYMMDDHH24MISS'
      )
    ),
    staging.fetched_at,
    coalesce(staging.raw_payload, '{}'::jsonb)
      || jsonb_build_object(
        'promoted_from', 'water_observations_staging',
        'staging_id', staging.id
      )
  from public.water_observations_staging staging
  join public.water_data_sources source_registry
    on source_registry.source_key = staging.source
   and source_registry.country_code = staging.country_code
   and source_registry.is_active
  join public.water_station_source_mappings mapping
    on mapping.source = staging.source
   and mapping.country_code = staging.country_code
   and mapping.source_station_id = staging.station_key
   and mapping.mapping_status = 'verified'
  where staging.source = 'AFDJ'
    and staging.country_code = 'RO'
  on conflict (
    source_id,
    source_entity_id,
    metric_code,
    source_record_fingerprint
  ) do nothing;

  get diagnostics inserted_rows = row_count;
  return inserted_rows;
end;
$$;

revoke all
  on function public.promote_afdj_water_level_observations()
  from public, anon, authenticated;

grant execute
  on function public.promote_afdj_water_level_observations()
  to service_role;

select public.promote_afdj_water_level_observations();

do $$
declare
  promoted_station_count integer;
begin
  select count(distinct observation.station_id)
  into promoted_station_count
  from public.water_operational_observations observation
  join public.water_data_sources source_registry
    on source_registry.id = observation.source_id
  where source_registry.source_key = 'AFDJ'
    and source_registry.country_code = 'RO'
    and observation.metric_code = 'water_level_cm'
    and observation.availability_status = 'available';

  if promoted_station_count <> 23 then
    raise exception
      'AFDJ promotion postcondition failed: expected 23 stations, found %.',
      promoted_station_count;
  end if;
end;
$$;

-- Stable mobile read contract. Raw and operational tables remain private.
create or replace function public.get_water_station_latest_v1(
  p_station_id text default null
)
returns table (
  station_id text,
  station_name text,
  river_name text,
  latitude double precision,
  longitude double precision,
  display_order integer,
  level_cm numeric,
  observed_at timestamptz,
  observed_at_precision text,
  source_key text,
  source_name text,
  source_url text,
  quality_status text,
  confidence text,
  fetched_at timestamptz,
  freshness_minutes integer,
  is_stale boolean
)
language sql
stable
security definer
set search_path = public, extensions
as $$
  with ranked as (
    select
      observation.*,
      source_registry.source_key,
      source_registry.display_name as source_name,
      source_registry.freshness_target_minutes,
      row_number() over (
        partition by observation.station_id
        order by
          observation.observed_at desc nulls last,
          observation.fetched_at desc,
          observation.created_at desc
      ) as row_rank
    from public.water_operational_observations observation
    join public.water_data_sources source_registry
      on source_registry.id = observation.source_id
     and source_registry.country_code = observation.country_code
     and source_registry.is_active
    where observation.station_id is not null
      and observation.metric_code = 'water_level_cm'
      and observation.availability_status = 'available'
      and observation.quality_status in ('validated', 'corrected')
      and (
        p_station_id is null
        or observation.station_id = p_station_id
      )
  )
  select
    station.id,
    station.name,
    station.river,
    station.latitude,
    station.longitude,
    station.display_order,
    latest.value,
    latest.observed_at,
    latest.observed_at_precision,
    latest.source_key,
    latest.source_name,
    latest.source_url,
    latest.quality_status,
    latest.confidence,
    latest.fetched_at,
    floor(
      greatest(
        0,
        extract(epoch from (now() - latest.observed_at)) / 60.0
      )
    )::integer,
    latest.observed_at <
      now() - make_interval(
        mins => coalesce(latest.freshness_target_minutes, 2160)
      )
  from ranked latest
  join public.stations station
    on station.id = latest.station_id
  where latest.row_rank = 1
  order by
    station.display_order nulls last,
    station.name;
$$;

