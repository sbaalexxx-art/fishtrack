create or replace function public.get_water_station_history_v1(
  p_station_id text,
  p_days integer default 30
)
returns table (
  station_id text,
  level_cm numeric,
  observed_at timestamptz,
  observed_at_precision text,
  source_key text,
  quality_status text,
  confidence text,
  fetched_at timestamptz,
  data_origin text
)
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
begin
  if p_station_id is null or btrim(p_station_id) = '' then
    raise exception 'Water history requires a station id.';
  end if;

  if p_days < 1 or p_days > 366 then
    raise exception 'Water history days must be between 1 and 366.';
  end if;

  return query
  with candidates as (
    select
      observation.station_id,
      observation.value as level_cm,
      observation.observed_at,
      observation.observed_at_precision,
      source_registry.source_key,
      observation.quality_status,
      observation.confidence,
      observation.fetched_at,
      'operational'::text as data_origin,
      1 as source_priority
    from public.water_operational_observations observation
    join public.water_data_sources source_registry
      on source_registry.id = observation.source_id
     and source_registry.country_code = observation.country_code
    where observation.station_id = p_station_id
      and observation.metric_code = 'water_level_cm'
      and observation.availability_status = 'available'
      and observation.quality_status in ('validated', 'corrected')
      and observation.observed_at >=
        now() - make_interval(days => p_days)

    union all

    select
      snapshot.station_id,
      snapshot.level_cm::numeric,
      coalesce(
        snapshot.level_measured_at,
        snapshot.observation_date::timestamp at time zone 'UTC'
      ),
      case
        when snapshot.level_measured_at is not null then 'exact'
        else 'date'
      end,
      coalesce(nullif(snapshot.level_source, ''), 'legacy_snapshot'),
      case lower(snapshot.quality)
        when 'valid' then 'validated'
        when 'partial' then 'raw'
        else 'suspect'
      end,
      case lower(snapshot.quality)
        when 'valid' then 'high'
        when 'partial' then 'medium'
        else 'low'
      end,
      snapshot.fetched_at,
      'daily_snapshot'::text,
      2
    from public.daily_water_snapshots snapshot
    where snapshot.station_id = p_station_id
      and snapshot.level_cm is not null
      and coalesce(
        snapshot.level_measured_at,
        snapshot.observation_date::timestamp at time zone 'UTC'
      ) >= now() - make_interval(days => p_days)
  ),
  ranked as (
    select
      candidate.*,
      row_number() over (
        partition by candidate.station_id, candidate.observed_at
        order by
          candidate.source_priority,
          candidate.fetched_at desc
      ) as row_rank
    from candidates candidate
  )
  select
    ranked.station_id,
    ranked.level_cm,
    ranked.observed_at,
    ranked.observed_at_precision,
    ranked.source_key,
    ranked.quality_status,
    ranked.confidence,
    ranked.fetched_at,
    ranked.data_origin
  from ranked
  where ranked.row_rank = 1
  order by ranked.observed_at asc;
end;
$$;

