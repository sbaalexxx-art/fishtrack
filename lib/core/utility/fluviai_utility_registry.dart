  static List<FluviUtilityDefinition> forFamily(FluviUtilityFamily family) =>
      definitions
          .where((definition) => definition.family == family)
          .toList(growable: false);

  static List<FluviUtilityDefinition> search(
    String query, {
    required bool isRomanian,
  }) {
    final normalized = query.trim().toLowerCase();
    if (normalized.isEmpty) return definitions;
    return definitions
        .where((definition) {
          final haystack = <String>[
            definition.id,
            definition.title(isRomanian),
            definition.subtitle(isRomanian),
            definition.family.title(isRomanian),
          ].join(' ').toLowerCase();
          return haystack.contains(normalized);
        })
        .toList(growable: false);
  }
