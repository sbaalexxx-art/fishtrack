import 'package:flutter/material.dart';

import '../navigation/app_destination.dart';

enum FluviUtilityFamily {
  waterIntelligence,
  mapExploration,
  weatherSolunar,
  fluviAi,
  communityReports,
  catchesJournal,
  myWatersFavorites,
  rulesPermitsSafety,
  accountSettings,
}

enum FluviEntitlementPolicy { free, premiumDepth, premiumOnly }

enum FluviOfflinePolicy { onlineOnly, cachedRead, queuedWrite, localFirst }

enum FluviPrivacyPolicy {
  notApplicable,
  privateDefault,
  exactApproximateHidden,
  aggregatedOnly,
}

enum FluviUtilityMaturity { beta, progressive }

class FluviUtilityDefinition {
  const FluviUtilityDefinition({
    required this.id,
    required this.family,
    required this.destination,
    required this.titleRo,
    required this.titleEn,
    required this.subtitleRo,
    required this.subtitleEn,
    required this.icon,
    required this.contexts,
    required this.countryPacks,
    required this.entitlement,
    required this.offlinePolicy,
    required this.privacyPolicy,
    this.permissions = const <String>{},
    this.searchable = true,
    this.pinnable = true,
    this.quickAction = false,
    this.safetyCritical = false,
    this.maturity = FluviUtilityMaturity.beta,
  });

  final String id;
  final FluviUtilityFamily family;
  final AppDestination destination;
  final String titleRo;
  final String titleEn;
  final String subtitleRo;
  final String subtitleEn;
  final IconData icon;
  final Set<String> contexts;
  final Set<String> countryPacks;
  final FluviEntitlementPolicy entitlement;
  final FluviOfflinePolicy offlinePolicy;
  final FluviPrivacyPolicy privacyPolicy;
  final Set<String> permissions;
  final bool searchable;
  final bool pinnable;
  final bool quickAction;
  final bool safetyCritical;
  final FluviUtilityMaturity maturity;

  String title(bool isRomanian) => isRomanian ? titleRo : titleEn;

  String subtitle(bool isRomanian) => isRomanian ? subtitleRo : subtitleEn;
}

extension FluviUtilityFamilyCopy on FluviUtilityFamily {
  String title(bool isRomanian) => switch (this) {
    FluviUtilityFamily.waterIntelligence =>
      isRomanian ? 'Inteligența apei' : 'Water Intelligence',
    FluviUtilityFamily.mapExploration =>
      isRomanian ? 'Hartă și explorare' : 'Map & Exploration',
    FluviUtilityFamily.weatherSolunar =>
      isRomanian ? 'Vreme și solunar' : 'Weather & Solunar',
    FluviUtilityFamily.fluviAi => isRomanian ? 'Fluvi și AI' : 'Fluvi & AI',
    FluviUtilityFamily.communityReports =>
      isRomanian ? 'Comunitate și rapoarte' : 'Community & Reports',
    FluviUtilityFamily.catchesJournal =>
      isRomanian ? 'Capturi și jurnal' : 'Catches & Journal',
    FluviUtilityFamily.myWatersFavorites =>
      isRomanian ? 'Apele mele și favorite' : 'My Waters & Favorites',
    FluviUtilityFamily.rulesPermitsSafety =>
      isRomanian ? 'Reguli, permise și siguranță' : 'Rules, Permits & Safety',
    FluviUtilityFamily.accountSettings =>
      isRomanian ? 'Cont și setări' : 'Account & Settings',
