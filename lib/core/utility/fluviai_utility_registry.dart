  IconData get icon => switch (this) {
    FluviUtilityFamily.waterIntelligence => Icons.water_rounded,
    FluviUtilityFamily.mapExploration => Icons.map_rounded,
    FluviUtilityFamily.weatherSolunar => Icons.cloud_rounded,
    FluviUtilityFamily.fluviAi => Icons.auto_awesome_rounded,
    FluviUtilityFamily.communityReports => Icons.groups_rounded,
    FluviUtilityFamily.catchesJournal => Icons.set_meal_rounded,
    FluviUtilityFamily.myWatersFavorites => Icons.bookmark_rounded,
    FluviUtilityFamily.rulesPermitsSafety => Icons.health_and_safety_rounded,
    FluviUtilityFamily.accountSettings => Icons.tune_rounded,
  };
}

